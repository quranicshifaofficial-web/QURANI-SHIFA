async function compressImageToDataUrl(file: File, maxDim = 1200, maxBytes = 140000): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = () => reject(new Error('Failed to read image file.'));
    reader.onload = () => {
      const img = new Image();
      img.onerror = () => reject(new Error('Invalid image file.'));
      img.onload = () => {
        const canvas = document.createElement('canvas');
        let { width, height } = img;
        if (width > maxDim || height > maxDim) {
          const ratio = Math.min(maxDim / width, maxDim / height);
          width = Math.round(width * ratio);
          height = Math.round(height * ratio);
        }
        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          reject(new Error('Canvas context unavailable.'));
          return;
        }
        ctx.drawImage(img, 0, 0, width, height);

        let quality = 0.82;
        let dataUrl = canvas.toDataURL('image/webp', quality);
        if (!dataUrl.startsWith('data:image/webp')) {
          dataUrl = canvas.toDataURL('image/jpeg', quality);
        }
        while (dataUrl.length > maxBytes && quality > 0.35) {
          quality -= 0.12;
          dataUrl = canvas.toDataURL('image/jpeg', quality);
        }
        if (dataUrl.length > 280000) {
          reject(new Error('Image is too large even after compression. Please choose a smaller file.'));
          return;
        }
        resolve(dataUrl);
      };
      img.src = String(reader.result);
    };
    reader.readAsDataURL(file);
  });
}

export async function uploadImageAsset(
  file: File,
  folder: string
): Promise<{ url: string; storageUsed: boolean }> {
  const safeName = file.name.replace(/[^a-zA-Z0-9._-]/g, '_');
  const objectRef = ref(storage, `qurani-shifa/${folder}/${Date.now()}_${safeName}`);

  try {
    const uploadPromise = (async () => {
      await uploadBytes(objectRef, file, { contentType: file.type || 'image/jpeg' });
      return getDownloadURL(objectRef);
    })();
    const timeoutPromise = new Promise<never>((_, reject) =>
      setTimeout(() => reject(new Error('Storage upload timeout')), 6500)
    );
    const url = await Promise.race([uploadPromise, timeoutPromise]);
    return { url, storageUsed: true };
  } catch {
    const compressedUrl = await compressImageToDataUrl(file);
    return { url: compressedUrl, storageUsed: false };
  }
}
